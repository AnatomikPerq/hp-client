"""Bundles Twemoji images for the icons taken from server names.

    python tool/twemoji.py <twemoji checkout>/assets/72x72

Every emoji goes to assets/emoji/<key>.png, where the key is the code points
in lowercase hex joined by "-" with U+FE0F left out, so a name matches with
or without the variation selector. Country flags (pairs of regional
indicators) go to assets/flags/<iso>.png, which CountryFlag also uses for
measured locations. lib/pages/shared/widgets/twemoji_keys.dart lists the keys
for the matcher in name_emoji.dart.

Source: https://github.com/jdecked/twemoji (v15.1.0), graphics CC-BY 4.0.
"""

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EMOJI = ROOT / "assets" / "emoji"
FLAGS = ROOT / "assets" / "flags"
KEYS = ROOT / "lib" / "pages" / "shared" / "widgets" / "twemoji_keys.dart"
VERSION = "15.1.0"
REGIONAL = range(0x1F1E6, 0x1F200)


def main() -> None:
    source = Path(sys.argv[1])
    files = sorted(source.glob("*.png"))
    if not files:
        raise SystemExit(f"no PNG files in {source}")
    shutil.rmtree(EMOJI, ignore_errors=True)
    EMOJI.mkdir(parents=True)
    keys: list[str] = []
    longest = 0
    for file in files:
        points = [int(part, 16) for part in file.stem.split("-")]
        if len(points) == 2 and all(point in REGIONAL for point in points):
            iso = "".join(chr(point - REGIONAL.start + ord("a")) for point in points)
            target = FLAGS / f"{iso}.png"
            if not target.exists():
                shutil.copyfile(file, target)
            continue
        stripped = [point for point in points if point != 0xFE0F]
        key = "-".join(f"{point:x}" for point in stripped)
        target = EMOJI / f"{key}.png"
        if target.exists():
            raise SystemExit(f"two images for {key}")
        shutil.copyfile(file, target)
        keys.append(key)
        longest = max(longest, len(stripped))
    keys.sort()
    chunks: list[str] = []
    line = ""
    for key in keys:
        candidate = f"{line} {key}" if line else key
        if len(candidate) > 70:
            chunks.append(line + " ")
            line = key
        else:
            line = candidate
    chunks.append(line)
    body = "\n".join(f"    '{chunk}'" for chunk in chunks)
    KEYS.write_text(
        f"// Generated by tool/twemoji.py from Twemoji {VERSION}. Do not edit.\n"
        "\n"
        "/// Every image in `assets/emoji/`, named by its key: code points in\n"
        "/// lowercase hex joined by `-`, without U+FE0F. Country flags are in\n"
        "/// `assets/flags/` instead.\n"
        "const twemojiKeys =\n"
        f"{body};\n"
        "\n"
        "/// The longest key, in code points.\n"
        f"const twemojiMaxLength = {longest};\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{len(keys)} emoji, longest {longest} code points")


if __name__ == "__main__":
    main()
